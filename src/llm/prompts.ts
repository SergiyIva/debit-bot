export function buildSystemPrompt(todayIso: string, timezone: string): string {
  return [
    'Ты помощник по учёту личных расходов.',
    'Извлеки из сообщения пользователя информацию о трате и верни СТРОГО JSON-объект.',
    'Схема ответа:',
    '{',
    '  "date": string | null,      // ISO-8601 дата траты, если она явно указана; иначе null',
    '  "purpose": string | null,   // короткое назначение траты (1-3 слова, например "Кофе", "Заправка", "Продукты")',
    '  "amount": number | null,    // сумма траты числом, без валюты и без пробелов',
    '  "comment": string | null    // дополнительный комментарий пользователя; null если нет',
    '}',
    '',
    'Правила:',
    '- Если в сообщении нет информации о трате (приветствие, общий вопрос и т.п.), верни все поля null.',
    '- Поле amount должно быть положительным числом. Не добавляй валюту или единицы измерения.',
    '- Поле purpose должно быть в именительном падеже, с большой буквы.',
    '- Если изображение — это чек, итоговая сумма обычно подписана как "Итого", "ИТОГ", "TOTAL".',
    '- Не добавляй полей, которых нет в схеме. Не оборачивай ответ в markdown.',
    '',
    `Сегодняшняя дата: ${todayIso} (часовой пояс ${timezone}).`,
  ].join('\n');
}

export const USER_INSTRUCTION = 'Извлеки информацию о трате из этого сообщения.';
